// Source: https://huggingface.co/datasets/RepDB/exercise-dataset
//
// Only the 50 seeded slugs are kept so the bundle stays small.
// Usage: node scripts/import-exercise-guides.mjs "<path to exercises.json>"

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC =
  process.argv[2] ?? path.join(process.env.TEMP, "repdb", "exercises.json");
const COVERAGE = path.resolve(ROOT, "../../design/repdb-coverage.json");
const OUT = path.join(ROOT, "src", "features", "training", "exerciseGuides.generated.ts");

const { result } = JSON.parse(fs.readFileSync(COVERAGE, "utf8"));
const wanted = new Set(result.filter((r) => r.slug).map((r) => r.slug));

const dataset = JSON.parse(fs.readFileSync(SRC, "utf8"));
const byId = new Map(dataset.exercises.map((e) => [e.id, e]));

const kept = [];
for (const slug of wanted) {
  const e = byId.get(slug);
  if (!e) {
    console.warn(`missing in dataset: ${slug}`);
    continue;
  }
  kept.push({
    slug,
    description: e.description_en ?? null,
    steps: e.instructions_en ?? [],
    tips: e.tips_en ?? [],
    difficulty: e.difficulty ?? null,
    mechanic: e.mechanic ?? null,
    force: e.force_type ?? null,
    unilateral: Boolean(e.is_unilateral),
  });
}

const entries = kept
  .map(
    (e) => `  '${e.slug}': {
    description: ${JSON.stringify(e.description)},
    steps: ${JSON.stringify(e.steps)},
    tips: ${JSON.stringify(e.tips)},
    difficulty: ${JSON.stringify(e.difficulty)},
    mechanic: ${JSON.stringify(e.mechanic)},
    force: ${JSON.stringify(e.force)},
    unilateral: ${e.unilateral},
  },`,
  )
  .join("\n");

const file = `// GENERATED by scripts/import-exercise-guides.mjs — do not edit by hand.
//
// Instruction text: RepDB (https://repdb.co), free tier, RepDB Free Tier
// License v1.0. Attribution is shown in Settings → About.
export type ExerciseGuide = {
  description: string | null;
  steps: string[];
  tips: string[];
  difficulty: string | null;
  mechanic: string | null;
  force: string | null;
  unilateral: boolean;
};

export const EXERCISE_GUIDES: Record<string, ExerciseGuide> = {
${entries}
};

export function guideFor(slug?: string | null): ExerciseGuide | null {
  if (!slug) return null;
  return EXERCISE_GUIDES[slug] ?? null;
}
`;

fs.writeFileSync(OUT, file);
console.log(`wrote ${kept.length} guides to ${path.relative(ROOT, OUT)}`);
