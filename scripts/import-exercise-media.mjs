//
// Usage: node scripts/import-exercise-media.mjs
// Re-run only when the seeded 50 change.

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const COVERAGE = path.resolve(ROOT, "../../design/repdb-coverage.json");
const OUT_DIR = path.join(ROOT, "assets", "images", "exercises");
const GEN_FILE = path.join(ROOT, "src", "features", "training", "exerciseMedia.generated.ts");

const HF = "https://huggingface.co/datasets/RepDB/exercise-dataset/resolve/main";
const LIST_URL = `${HF}/../exercise-list.json`;
const REPO_API = "https://huggingface.co/api/datasets/RepDB/exercise-dataset";

const { result } = JSON.parse(fs.readFileSync(COVERAGE, "utf8"));
const mapped = result.filter((r) => r.slug);

// The list of files the repo actually ships, so we never guess a filename.
const repo = await (await fetch(REPO_API)).json();
const files = new Set(repo.siblings.map((s) => s.rfilename));

const pick = (slug) => {
  const start = `images/flat/${slug}-start.webp`;
  const peak = `images/flat/${slug}-peak.webp`;
  const main = `images/flat/${slug}-main.webp`;
  if (files.has(start) && files.has(peak)) return { start, peak, single: false };
  if (files.has(main)) return { start: main, peak: null, single: true };
  return null;
};

fs.mkdirSync(OUT_DIR, { recursive: true });

const entries = [];
const skipped = [];

for (const row of mapped) {
  const found = pick(row.slug);
  if (!found) {
    skipped.push(row);
    continue;
  }

  const local = [];
  for (const key of ["start", "peak"]) {
    const remote = found[key];
    if (!remote) {
      local.push(null);
      continue;
    }
    const name = path.basename(remote);
    const dest = path.join(OUT_DIR, name);
    if (!fs.existsSync(dest)) {
      const res = await fetch(`${HF}/${remote}`);
      if (!res.ok) throw new Error(`${remote} -> HTTP ${res.status}`);
      fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
      process.stdout.write(`  ${name} ${(fs.statSync(dest).size / 1024).toFixed(0)} KB\n`);
    }
    local.push(name);
  }

  entries.push({
    slug: row.slug,
    name: row.name,
    start: local[0],
    peak: local[1],
    single: found.single,
  });
}

const requires = (file) =>
  file ? `require('../../../assets/images/exercises/${file}')` : "null";

const body = entries
  .map(
    (e) => `  '${e.slug}': {
    start: ${requires(e.start)},
    peak: ${requires(e.peak)},
  },`,
  )
  .join("\n");

const nameMap = entries
  .map((e) => `  ${JSON.stringify(e.name)}: '${e.slug}',`)
  .join("\n");

const generated = `// GENERATED by scripts/import-exercise-media.mjs — do not edit by hand.
//
// Still images: RepDB (https://repdb.co), free tier, used under the RepDB Free
// Tier License v1.0. Attribution is shown in Settings → About.
export type ExerciseStill = {
  /** Start (or only) pose. Metro resolves require() to a numeric asset id. */
  start: number;
  /** Peak pose; null for static holds. */
  peak: number | null;
};

export const EXERCISE_STILLS: Record<string, ExerciseStill> = {
${body}
};

/**
 * Fallback for rows that predate the \`slug\` column. The server value wins;
 * this keeps images working while older local caches are still around.
 */
export const SLUG_BY_NAME: Record<string, string> = {
${nameMap}
};

/** Static holds and stretches ship a single frame. */
export function stillsFor(slug?: string | null): ExerciseStill | null {
  if (!slug) return null;
  return EXERCISE_STILLS[slug] ?? null;
}
`;

fs.writeFileSync(GEN_FILE, generated);

console.log(
  `\n${entries.length} exercises imported, ${skipped.length} skipped` +
    (skipped.length ? `: ${skipped.map((s) => s.name).join(", ")}` : ""),
);
console.log(`Wrote ${path.relative(ROOT, GEN_FILE)}`);
